SVG_ROOT_RE = re.compile(r"^\s*<svg\b([^>]*)>", re.S)


def read_svg(path: Path) -> str:
    text = path.read_text(encoding="utf-8").strip()
    text = re.sub(r"^<\?xml[^>]*\?>\s*", "", text)
    text = re.sub(r"^<!DOCTYPE[^>]*>\s*", "", text, flags=re.I)
    return text


def natural_size(text: str, path: Path) -> tuple[float, float]:
    m = SVG_ROOT_RE.match(text)
    if not m:
        raise ValueError(f"{path}: не нашёл корневой тег <svg>")
    attrs = m.group(1)
    w = re.search(r'\bwidth="([\d.]+)"', attrs)
    h = re.search(r'\bheight="([\d.]+)"', attrs)
    if w and h:
        return float(w.group(1)), float(h.group(1))
    vb = re.search(r'\bviewBox="([-\d.\s]+)"', attrs)
    if not vb:
        raise ValueError(f"{path}: нет ни width/height, ни viewBox")
    parts = [float(x) for x in vb.group(1).split()]
    return parts[2], parts[3]


def uniquify_ids(text: str, uid: str) -> str:
    """Развести id между копиями одного файла на одной странице."""
    for ident in sorted(set(re.findall(r'\bid="([^"]+)"', text)), key=len, reverse=True):
        new = f"{ident}-{uid}"
        text = text.replace(f'id="{ident}"', f'id="{new}"')
        text = text.replace(f"url(#{ident})", f"url(#{new})")
        text = text.replace(f'href="#{ident}"', f'href="#{new}"')
    return text


def rewrite_root(text: str, *, width=None, height=None, decorative=False,
                 add_class: str | None = None) -> str:
    def repl(m: re.Match) -> str:
        attrs = m.group(1)
        if width is not None:
            attrs = re.sub(r'\s(?:width|height)="[^"]*"', "", attrs)
        if add_class:
            if re.search(r'\bclass="', attrs):
                attrs = re.sub(r'\bclass="([^"]*)"', lambda c: f'class="{c.group(1)} {add_class}"', attrs)
            else:
                attrs += f' class="{add_class}"'
        tail = ""
        if width is not None:
            tail += f' width="{width:g}" height="{height:g}"'
        if decorative:
            attrs = re.sub(r'\srole="[^"]*"', "", attrs)
            attrs = re.sub(r'\saria-label="[^"]*"', "", attrs)
            tail += ' aria-hidden="true" focusable="false"'
        return f"<svg{attrs}{tail}>"

    return SVG_ROOT_RE.sub(repl, text, count=1)


def render_svg(path: Path, uid: str, height: float, *, decorative=True) -> str:
    text = read_svg(path)
    nw, nh = natural_size(text, path)
    text = uniquify_ids(text, uid)
    w = round(nw / nh * height, 2)
    return rewrite_root(text, width=w, height=height, decorative=decorative)


def namespace_anim(text: str, tokens) -> str:
    for pattern, replacement in tokens:
        if pattern.startswith(r"\b"):
            text = re.sub(pattern, replacement, text)
        else:
            text = text.replace(pattern, replacement)
    return text


def human_size(n: int) -> str:
    if n < 1024:
        return f"{n} Б"
    return f"{n / 1024:.1f} КБ".replace(".", ",")


