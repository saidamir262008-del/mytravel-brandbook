def main() -> int:
    site = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_SITE
    lab = site / "logo-lab"
    if not lab.is_dir():
        print(f"нет папки {lab}", file=sys.stderr)
        return 1

    written = [build_root(lab)]
    for d in DIRECTIONS:
        folder = lab / d["slug"]
        if not folder.is_dir():
            print(f"пропускаю {folder}: папки нет", file=sys.stderr)
            continue
        for v in d["variants"]:
            if not (folder / v["file"]).exists():
                print(f"нет файла {folder / v['file']}", file=sys.stderr)
                return 1
        written.append(build_direction(lab, d))
    if (lab / "anim").is_dir():
        written.append(build_anim(lab))

    for p in written:
        print(f"{p}  {p.stat().st_size:>7} Б")
    print(f"\nвсего страниц: {len(written)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
